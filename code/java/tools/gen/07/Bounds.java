public class Bounds {
    public static void main(String[] args) {
        int[] values = {10, 20, 30};
        System.out.println("length           = " + values.length);
        System.out.println("last valid index = " + (values.length - 1));
        System.out.println("reading index 3:");
        System.out.println(values[3]);
    }
}
