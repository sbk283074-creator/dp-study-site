"""Chapter 20 -- --dry-run is only honest if it calls the same plan.

A directory of eight text files and a job that puts a header line on each one.
The job is run four times with and without the flag. The count is of files
changed, against the number the plan said would change.
"""

import pathlib
import tempfile

FILES = 8
HEADER = "# generated by tidy\n"


def build(directory):
    for index in range(FILES):
        path = directory / f"note-{index}.txt"
        path.write_text(f"line one of note {index}\n", encoding="utf-8")
    return directory


def plan(directory):
    """The files that need work: any whose first line is not the header."""
    todo = []
    for path in sorted(directory.iterdir()):
        if path.suffix != ".txt":
            continue
        if not path.read_text(encoding="utf-8").startswith(HEADER):
            todo.append(path)
    return todo


def apply(directory):
    changed = 0
    for path in plan(directory):
        text = path.read_text(encoding="utf-8")
        path.write_text(HEADER + text, encoding="utf-8")
        changed += 1
    return changed


def with_header(directory):
    return sum(1 for path in sorted(directory.iterdir())
               if path.suffix == ".txt"
               and path.read_text(encoding="utf-8").startswith(HEADER))


directory = build(pathlib.Path(tempfile.mkdtemp()))

rows = []

planned = len(plan(directory))
rows.append(("first pass, --dry-run", planned, 0, with_header(directory)))

changed = apply(directory)
rows.append(("first pass, applied", planned, changed, with_header(directory)))

planned = len(plan(directory))
changed = apply(directory)
rows.append(("second pass, applied", planned, changed, with_header(directory)))

planned = len(plan(directory))
rows.append(("third pass, --dry-run", planned, 0, with_header(directory)))

print(f"{FILES} text files, and a job that puts a header line on each")
print()
print(f"{'pass':<26}{'planned':>10}{'changed':>10}{'files with header':>20}")
print("-" * 66)
for label, planned, changed, done in rows:
    print(f"{label:<26}{planned:>10}{changed:>10}{done:>20}")

print()
print(f"{'what is counted':<40}{'count':>8}")
print("-" * 52)
print(f"{'files in the directory':<40}{FILES:>8}")
print(f"{'files that needed work at the start':<40}{rows[0][1]:>8}")
print(f"{'files that needed work after the first pass':<40}{rows[2][1]:>8}")
print(f"{'passes that changed nothing':<40}"
      f"{sum(1 for _, _, changed, _ in rows if changed == 0):>8}")
print(f"{'files with the header at the end':<40}{rows[-1][3]:>8}")

print()
print("The first row is the flag doing its job. Eight files need work, the")
print("plan says eight, and nothing is written -- so the person running it can")
print("look at the list before anything moves. That only means something if the")
print("dry run and the real run ask the same question, which is why both call")
print("`plan()` here. A flag that reimplements the logic is a second program,")
print("and it will disagree with the first one eventually.")
print()
print("The second and third rows are idempotency, and they are the reason a")
print("job like this can be run from cron at all. The second pass finds")
print("nothing to do and changes nothing, so running the job twice is the same")
print("as running it once. Without that property a scheduled job is a job you")
print("cannot re-run after a crash: you do not know which half already")
print("happened, and doing it again makes it worse.")
print()
print("The way to get it is to make the job ask 'is this already done?' rather")
print("than 'have I run yet?'. A marker file, a header line, a row in a table")
print("-- something the job can read back and compare. State you have to")
print("remember is state you will lose; state you can observe is state you can")
print("resume from.")
